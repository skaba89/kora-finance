import { expect, test } from "@playwright/test";
import { createCompany, registerAndLogin } from "./helpers";

test("achats : brouillon fournisseur, préférences du tableau et accès à l'échéancier", async ({ page }, testInfo) => {
  await registerAndLogin(page);
  const id = await createCompany(page, "Commerce des achats");
  await page.goto(`/dossiers/${id}/tiers`);
  await page.getByRole("textbox", { name: "Nom / raison sociale" }).fill("Fournisseur de Madina");
  await page.getByRole("checkbox", { name: "Fournisseur", exact: true }).check();
  await page.getByRole("button", { name: "Enregistrer", exact: true }).click();
  await expect(page.getByRole("row").filter({ hasText: "Fournisseur de Madina" })).toBeVisible();
  await page.goto(`/dossiers/${id}/achats`);
  await page.getByRole("link", { name: "Nouvelle facture d'achat (brouillon)" }).click();
  const create = page.locator("#nouvel-achat");
  const supplier = create.getByRole("combobox", { name: "Fournisseur", exact: true });
  await expect(supplier).toBeVisible();
  await expect(page.getByRole("combobox", { name: "Tier fournisseur", exact: true })).toBeVisible();
  await expect(page.locator("#achat-document-fournisseur")).toHaveCount(1);
  await supplier.selectOption({ label: "Fournisseur de Madina" });
  const line = create.getByRole("group", { name: "Ligne 1", exact: true });
  await line.getByLabel("Désignation").fill("Marchandises");
  await line.getByLabel("Quantité").fill("1");
  await line.getByLabel("Prix unitaire HT (unités)").fill("850000");
  await page.getByRole("button", { name: "Créer le brouillon" }).click();
  const row = page.getByRole("row").filter({ hasText: "Fournisseur de Madina" });
  await expect(row).toContainText(/850\s000 GNF/);
  await expect(row).toContainText("Brouillon");
  await page.getByRole("combobox", { name: "Taille de page" }).selectOption("25");
  await page.getByRole("combobox", { name: "Densité du tableau" }).selectOption("compact");
  await page.getByRole("button", { name: "Filtrer", exact: true }).click();
  await expect(page).toHaveURL(/densite=compact/);
  await expect(row).toContainText(/850\s000 GNF/);
  await testInfo.attach("achats-premium", { body: await page.screenshot(), contentType: "image/png" });
  await page.getByRole("link", { name: "Réinitialiser les filtres" }).click();
  await expect(page.getByRole("combobox", { name: "Taille de page" })).toHaveValue("50");
  await expect(page.getByRole("combobox", { name: "Densité du tableau" })).toHaveValue("comfortable");
  await page.getByRole("combobox", { name: "Statut", exact: true }).selectOption("ISSUED");
  await page.getByRole("button", { name: "Filtrer", exact: true }).click();
  await expect(page.locator("#documents-achats")).toContainText("Aucun document d'achat à afficher.");
  await page.getByRole("link", { name: "Réinitialiser les filtres" }).click();
  await expect(row).toContainText(/850\s000 GNF/);
  await page.getByRole("navigation", { name: "Achats", exact: true }).getByRole("link", { name: "Échéancier fournisseurs" }).click();
  await expect(page.locator("#echeancier")).toContainText("Aucune dette non soldée");
});
